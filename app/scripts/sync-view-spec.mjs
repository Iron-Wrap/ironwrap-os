#!/usr/bin/env node
// Copies app/src/generated-views/view-spec.ts into the Worker as workers-bus/src/agents/view-spec.ts:
// a two-line header, then the exact bytes, so the ask API and the app validate a view spec with the
// same code. `--check` fails when the copy is stale.
//   node scripts/sync-view-spec.mjs [--check]

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";

export const VIEW_SPEC_SOURCE = fileURLToPath(
  new URL("../src/generated-views/view-spec.ts", import.meta.url),
);
export const WORKER_VIEW_SPEC = fileURLToPath(
  new URL("../../workers-bus/src/agents/view-spec.ts", import.meta.url),
);

const HEADER = [
  "// Generated by app/scripts/sync-view-spec.mjs. Do not edit.",
  "// Change app/src/generated-views/view-spec.ts, then run `npm run view-spec` in app/.",
  "",
].join("\n");

export function renderWorkerCopy(source) {
  return `${HEADER}${source}`;
}

if (fileURLToPath(import.meta.url) === resolve(process.argv[1] ?? "")) {
  const expected = renderWorkerCopy(readFileSync(VIEW_SPEC_SOURCE, "utf8"));
  if (process.argv.includes("--check")) {
    if (!existsSync(WORKER_VIEW_SPEC) || readFileSync(WORKER_VIEW_SPEC, "utf8") !== expected) {
      console.error("workers-bus/src/agents/view-spec.ts is stale; run npm run view-spec");
      process.exit(1);
    }
  } else {
    writeFileSync(WORKER_VIEW_SPEC, expected);
  }
}
