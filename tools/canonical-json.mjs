// Canonical JSON for release permits and promotion records. Keys sort with
// localeCompare and undefined members drop, so every hash already issued stays
// reproducible; tools/canonical-json.test.mjs pins the output byte for byte.
export function canonicalJson(value) {
  return JSON.stringify(canonicalize(value));
}

function canonicalize(value) {
  if (Array.isArray(value)) return value.map(canonicalize);
  if (value && typeof value === "object") {
    return Object.fromEntries(
      Object.entries(value)
        .filter(([, child]) => child !== undefined)
        .sort(([a], [b]) => a.localeCompare(b))
        .map(([key, child]) => [key, canonicalize(child)]),
    );
  }
  return value;
}
