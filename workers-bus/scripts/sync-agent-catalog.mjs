#!/usr/bin/env node
// Copies the machine-readable block of docs/AI-TEAM-CONTRACT.md into the Worker bundle, byte for
// byte, so the Worker enforces exactly the catalog the contract states and the catalog hash it
// records matches the one the playbooks and evals pin. `--check` fails when the copy is stale.
//   node scripts/sync-agent-catalog.mjs [--check]

import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const CONTRACT = fileURLToPath(new URL("../../docs/AI-TEAM-CONTRACT.md", import.meta.url));
const TARGET = fileURLToPath(new URL("../src/agents/contract-catalog.ts", import.meta.url));

export function extractCatalogJson(markdown) {
  const start = markdown.indexOf("<!-- ai-team-contract:start -->");
  const end = markdown.indexOf("<!-- ai-team-contract:end -->");
  if (start === -1 || end <= start) throw new Error("ai-team-contract markers not found");
  const json = markdown.slice(start, end).match(/```json\s*([\s\S]*?)\s*```/)?.[1];
  if (!json) throw new Error("ai-team-contract block has no JSON fence");
  JSON.parse(json);
  return json;
}

export function renderCatalogModule(json) {
  const sha256 = createHash("sha256").update(json).digest("hex");
  return [
    "// Generated by workers-bus/scripts/sync-agent-catalog.mjs from docs/AI-TEAM-CONTRACT.md.",
    "// Do not edit: change the contract, then run `node scripts/sync-agent-catalog.mjs`.",
    `export const CATALOG_SHA256 = ${JSON.stringify(sha256)};`,
    `export const CATALOG_JSON = ${JSON.stringify(json)};`,
    "",
  ].join("\n");
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const expected = renderCatalogModule(extractCatalogJson(readFileSync(CONTRACT, "utf8")));
  if (process.argv.includes("--check")) {
    if (readFileSync(TARGET, "utf8") !== expected) {
      console.error("src/agents/contract-catalog.ts is stale; run node scripts/sync-agent-catalog.mjs");
      process.exit(1);
    }
  } else {
    writeFileSync(TARGET, expected);
  }
}
