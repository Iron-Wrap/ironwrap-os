/**
 * design/system-v2/TEMPLATES.md wording a literal rule refuses, pinned until Track B rewords it;
 * the app test pins the same paths. Empty: every copied example validates.
 */
const TEMPLATES_WORDING: Record<string, string[]> = {};

function depth(schema: JsonSchema, level = 0): number {
  const container = (child: unknown) =>
    typeof child === "object" &&
    child !== null &&
    [(child as JsonSchema).type]
      .flat()
      .some((type) => type === "object" || type === "array");
  const children = [
    ...Object.values((schema.properties ?? {}) as Record<string, JsonSchema>),
    ...(schema.items ? [schema.items as JsonSchema] : []),
  ];
  return Math.max(
    level,
    ...children.filter(container).map((child) => depth(child, level + 1)),
  );
}

test("the Worker validates a view spec with its own catalog", () => {
  assert.deepEqual(
    validateViewSpec(JSON.stringify(served), catalog, { place: "office" }),
    {
      ok: true,
      spec: served,
    },
  );
  const result = validateViewSpec(
    {
      ...served,
      specialist_id: "estimator",
      actions: [
        {
          action_id: "refund.issue",
          label: "Issue the credit",
          target: null,
          primary: false,
        },
      ],
    },
    catalog,
    { place: "office" },
  );
  assert.equal(result.ok, false);
  assert.deepEqual(
    new Set(!result.ok && result.issues.map((issue) => issue.code)),
    new Set(["specialist_not_face", "action_people_only"]),
  );
});

test("the JSON Schema export is in the gateway's strict dialect, at most six deep", () => {
  const all = everythingAvailable(READ_MODELS);
  for (const schema of [
    viewSpecJsonSchema(),
    viewSpecJsonSchema({ catalog, readModels: all }),
  ]) {
    assert.doesNotThrow(() => assertStrictSchema(schema));
    assert.ok(depth(schema) <= 6, `depth ${depth(schema)}`);
  }
});

test("a valid spec of every template conforms to the strict schema in its wire form", () => {
  const production = viewSpecJsonSchema({ catalog });
  const servedWire = toWireForm(served, production);
  assert.deepEqual(validate(production, servedWire), []);
  assert.equal(
    validateViewSpec(servedWire, catalog, { place: "office" }).ok,
    true,
  );
  const all = everythingAvailable(READ_MODELS);
  const schema = viewSpecJsonSchema({ catalog, readModels: all });
  for (const { file, spec } of examples) {
    const wire = toWireForm(spec, schema);
    assert.deepEqual(validate(schema, wire), [], file);
    const result = validateViewSpec(wire, catalog, {
      place: "office",
      readModels: all,
    });
    assert.deepEqual(
      result.ok
        ? []
        : result.issues.map((issue) => `${issue.code} ${issue.path}`),
      (TEMPLATES_WORDING[file] ?? []).map(
        (path) => `literal_has_number_words ${path}`,
      ),
      file,
    );
  }
  assert.equal(
    new Set(examples.map(({ spec }) => (spec as { template: string }).template))
      .size,
    6,
  );
});
